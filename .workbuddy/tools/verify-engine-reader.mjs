import assert from 'node:assert/strict'
import { Cdp, newTarget, preparePage, navigate, setFileInput } from './cdp-client.mjs'
const CDP_PORT = Number(process.env.CDP_PORT ?? 9341)
const APP_URL = process.env.APP_URL ?? 'http://127.0.0.1:5311/'
const PDF_PATH = process.argv[2]
const SHOT = process.argv[3] ?? 'tmp/engine-ui'
if (!PDF_PATH) throw new Error('Provide a PDF with a saved mono/dual pair')
const target = await newTarget(CDP_PORT)
const cdp = await Cdp.connect(target.webSocketDebuggerUrl)
await preparePage(cdp, {width: 1440, height: 960})
await navigate(cdp, APP_URL)
await cdp.waitFor('document.querySelector(".welcome-open")?.textContent', Boolean)
await cdp.screenshot(`${SHOT}-empty.png`)
const click = async text => cdp.eval(`(() => { const b = [...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(text)}); if(!b) throw Error('Missing button'); b.click(); })()`)
await setFileInput(cdp, PDF_PATH)
await cdp.waitFor('document.querySelector(".toolbar__document-meta")?.textContent', v=>/PAGES/.test(v ?? ''))
await cdp.waitFor('document.querySelector(".textLayer span")?.textContent', Boolean)
await cdp.screenshot(`${SHOT}-selection.png`)
await click('全文翻译')
await cdp.waitFor('document.querySelector(".full-controls .btn--primary")?.textContent.trim()', v=>v==='打开已有译本')
await click('打开已有译本')
await cdp.waitFor('document.querySelector(".reader-lane--translated .textLayer span")?.textContent', Boolean)
await cdp.waitFor('document.querySelector(".reader-status__path")?.textContent', v=>v?.includes('.dual.pdf'))
const ratio = await cdp.eval(`(()=>{const page=document.querySelector('.reader-lane--translated .pdf-page'); return page.offsetWidth/page.offsetHeight})()`)
assert.ok(ratio>1.4, `Dual page ratio ${ratio}`)
await cdp.screenshot(`${SHOT}-dual.png`)
await cdp.eval(`(()=>{let input=document.querySelector('.pager__input');input.value='3';input.dispatchEvent(new Event('input',{bubbles:true}));input.dispatchEvent(new KeyboardEvent('keyup',{key:'Enter',bubbles:true}))})()`)
await cdp.waitFor('document.querySelector(".pager__input")?.value',v=>v==='3')
await click('只看中文')
await cdp.waitFor('document.querySelector(".reader-status__path")?.textContent',v=>v?.includes('.mono.pdf'))
await cdp.waitFor('document.querySelector(".full-controls .btn--primary")?.textContent.trim()',v=>v==='译本已打开')
const monoRatio = await cdp.eval(`(()=>{const page=document.querySelector('.reader-lane--translated .pdf-page'); return page.offsetWidth/page.offsetHeight})()`)
assert.ok(monoRatio<1, `Mono page ratio ${monoRatio}`)
await cdp.waitFor('document.querySelector(".pager__input")?.value',v=>v==='3')
await cdp.waitFor(`document.querySelector('.reader-lane--translated [data-page-number="3"] canvas')?.width`,v=>v>100)
await cdp.screenshot(`${SHOT}-mono.png`)
await click('划词翻译'); await click('全文翻译')
await cdp.waitFor('document.querySelector(".reader-lane--translated")?.offsetWidth',v=>v>0)
await cdp.waitFor('document.querySelector(".pager__input")?.value',v=>v==='3')
await click('中英对照')
await cdp.waitFor('document.querySelector(".reader-status__path")?.textContent',v=>v?.includes('.dual.pdf'))
await cdp.waitFor('document.querySelector(".full-controls .btn--primary")?.textContent.trim()',v=>v==='译本已打开')
await cdp.waitFor(`document.querySelector('.reader-lane--translated [data-page-number="3"] canvas')?.width`,v=>v>100)
await click('设置')
await cdp.waitFor('document.querySelector(".dialog")?.textContent',Boolean)
await cdp.screenshot(`${SHOT}-settings.png`)
await cdp.send('Emulation.setDeviceMetricsOverride',{width:750,height:900,deviceScaleFactor:1,mobile:false})
await click('取消'); await click('适应宽度')
await cdp.waitFor('document.querySelector(".pager__input")?.value',v=>v==='3')
await cdp.waitFor(`document.querySelector('.reader-lane--translated [data-page-number="3"] canvas')?.width`,v=>v>100)
await cdp.screenshot(`${SHOT}-narrow.png`)
const errors = [...cdp.consoleErrors, ...cdp.exceptions, ...cdp.logEntries.filter(v=>v.includes('[error]'))]
assert.deepEqual(errors,[])
assert.equal(await cdp.eval('document.querySelector(".error-bar")?.textContent ?? ""'),'')
console.log(JSON.stringify({passed:true,dualRatio:ratio,monoRatio,selectionSwitchRetainsPage:true,translationRequests:cdp.requests.filter(u=>u.includes('/chat/completions')).length}))
await cdp.close()
